def blocos(dims, prefixo_versao=""):
    n, out = 0, []
    for dim, itens in dims.items():
        for texto in itens:
            n += 1
            cab = f"**** {prefixo_versao}*{dim} *item_{n:02d}"
            out.append(f"{cab}\n{texto}\n")
    return "\n".join(out)


